#!/usr/bin/env python3
"""Generate Unicode 16 string properties from pinned local emoji source files.

Normal builds use the committed Go output. Sources are available from
https://www.unicode.org/Public/emoji/16.0/ . See go/rhunext/LICENSE-Unicode.txt.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

from snippet_unicode import write_atomic

SOURCES = {
    'sequences': (192618, '3fe3c77e72e8f26df302dc7d99b106c5d08fd808ef7246fb5d4502d659fe659c'),
    'zwj': (251607, '9423ec235474356f970a696506737e2d5d65453a67f45df66b8bbe920c3fab83'),
}
COUNTS = {'Basic_Emoji': 1393, 'Emoji_Keycap_Sequence': 12,
          'RGI_Emoji_Flag_Sequence': 259, 'RGI_Emoji_Tag_Sequence': 3,
          'RGI_Emoji_Modifier_Sequence': 655, 'RGI_Emoji_ZWJ_Sequence': 1468}
HEX = re.compile(r'[0-9A-F]{4,6}\Z')


def scalar(text):
    if not HEX.fullmatch(text):
        raise ValueError('invalid hexadecimal scalar')
    cp = int(text, 16)
    if cp > 0x10ffff or 0xd800 <= cp <= 0xdfff:
        raise ValueError('invalid Unicode scalar')
    return cp


def records(text, allowed):
    """Parse bounded source records without depending on host Unicode data."""
    count = 0
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = [part.strip() for part in line.split(';')]
        if len(fields) != 3 or fields[1] not in allowed:
            raise ValueError('invalid emoji property record')
        words = fields[0].split()
        if len(words) == 1 and '..' in words[0]:
            bounds = words[0].split('..')
            if len(bounds) != 2:
                raise ValueError('invalid emoji range')
            lo, hi = map(scalar, bounds)
            if hi < lo or hi - lo > 4095 or lo <= 0xdfff and hi >= 0xd800:
                raise ValueError('invalid emoji range')
            values = (chr(cp) for cp in range(lo, hi + 1))
            size = hi - lo + 1
        else:
            if not 1 <= len(words) <= 10:
                raise ValueError('invalid emoji sequence length')
            values = (''.join(chr(scalar(word)) for word in words),)
            size = 1
        count += size
        if count > 8192:
            raise ValueError('too many emoji sequences')
        for value in values:
            yield fields[1], value


def read_source(path, kind):
    size, digest = SOURCES[kind]
    with Path(path).open('rb') as source:
        data = source.read(size + 1)
    if len(data) != size:
        raise ValueError('unexpected emoji source size')
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError('emoji source SHA256 mismatch')
    text = data.decode('utf-8')
    if '# Version: 16.0\n' not in text:
        raise ValueError('unexpected emoji source version')
    return text


def build_model(sequences, zwj, check_counts=True):
    props = {name: set() for name in COUNTS}
    for text, allowed in [(sequences, set(COUNTS) - {'RGI_Emoji_ZWJ_Sequence'}),
                          (zwj, {'RGI_Emoji_ZWJ_Sequence'})]:
        for name, word in records(text, allowed):
            if word in props[name]:
                raise ValueError('duplicate emoji sequence')
            props[name].add(word)
    if check_counts and any(len(props[name]) != count for name, count in COUNTS.items()):
        raise ValueError('unexpected emoji property counts')
    props['RGI_Emoji'] = set().union(*props.values())
    if check_counts and len(props['RGI_Emoji']) != 3790:
        raise ValueError('unexpected RGI emoji union count')
    return {name: sorted(words) for name, words in sorted(props.items())}


def emit_go(props):
    lines = ['// Code generated by tools/snippet_emoji.py; DO NOT EDIT.',
             '// Unicode 16.0. See LICENSE-Unicode.txt.', 'package rhunext', '',
             'var snippetEmojiProperties = map[string][]string{']
    for name, words in sorted(props.items()):
        lines.append(json.dumps(name) + ': {')
        # ASCII escapes make invisible emoji component characters reviewable.
        for word in words:
            escaped = ''.join('\\U%08x' % ord(cp) for cp in word)
            lines.append('"' + escaped + '",')
        lines.append('},')
    lines.append('}\n')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sequences')
    parser.add_argument('zwj')
    parser.add_argument('--go-out', required=True)
    args = parser.parse_args()
    paths = [Path(path).resolve() for path in [args.sequences, args.zwj, args.go_out]]
    if len(set(paths)) != 3:
        parser.error('source and output paths must be distinct')
    model = build_model(read_source(paths[0], 'sequences'), read_source(paths[1], 'zwj'))
    result = subprocess.run(['gofmt'], input=emit_go(model), text=True,
                            capture_output=True, check=True).stdout
    write_atomic(paths[2], result)


if __name__ == '__main__':
    main()
