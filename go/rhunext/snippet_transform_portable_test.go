type snippetPortableRow struct{ base, length, patch, value, valid, offset int }

func snippetPortableCases(t testing.TB) [][]byte {
	t.Helper()
	cases := snippetTransformPayloadValidationCases(t)
	setsRegex, err := compileSnippetRegex(`[\q{ab|abc|a|}]c`, "iv")
	if err != nil {
		t.Fatal(err)
	}
	sets := &snippetTransformPayload{bindings: []snippetTransformBinding{{1,
		setsRegex, replacementFixture()}}}
	setsRaw, setsErr := sets.encode()
	if setsErr != nil {
		t.Fatal(setsErr)
	}
	cases = append(cases, setsRaw)
	namesRegex, err := compileSnippetRegex(`(?:(?<é>a)|(?<\u00e9>b))\k<é>`, "v")
	if err != nil {
		t.Fatal(err)
	}
	names := &snippetTransformPayload{bindings: []snippetTransformBinding{{1, namesRegex, replacementFixture()}}}
	namesRaw, err := names.encode()
	if err != nil {
		t.Fatal(err)
	}
	cases = append(cases, namesRaw)
	legacyRegex, err := compileSnippetRegex(`(\141+)[a-\d](?=(a))?a`, "")
	if err != nil {
		t.Fatal(err)
	}
	legacy := &snippetTransformPayload{bindings: []snippetTransformBinding{{1, legacyRegex, replacementFixture()}}}
	legacyRaw, err := legacy.encode()
	if err != nil {
		t.Fatal(err)
	}
	cases = append(cases, legacyRaw)
	rich := &snippetTransformPayload{bindings: []snippetTransformBinding{{1, regexProgramFixture(), replacementFixture()}}}
	raw, e := rich.encode()
	if e != nil {
		t.Fatal(e)
	}
	cases = append(cases, raw)
	for n := 0; n < len(raw); n++ {
		cases = append(cases, bytes.Clone(raw[:n]))
	}
	for at := range raw {
		b := bytes.Clone(raw)
		b[at] ^= 255
		cases = append(cases, b)
	}
	roff := int(binary.LittleEndian.Uint32(raw[36:]))
	foff := int(binary.LittleEndian.Uint32(raw[44:]))
	for _, v := range []struct {
		at    int
		value uint32
	}{
		{roff + 16, 64}, {roff + 16, 65}, {roff + 52, 0x110000}, {roff + 52, 0xdfff}, {roff + 52, 0xffffffff},
		{roff + 132, 0xfffffffe}, {roff + 136, 0xfffffffe}, {roff + 272, 0xffffffff},
		{foff + 44, 1}, {foff + 12, 8192}, {foff + 12, 8193}, {foff + 16, 0xffffffff},
	} {
		b := bytes.Clone(raw)
		binary.LittleEndian.PutUint32(b[v.at:], v.value)
		cases = append(cases, b)
	}
	p := regexProgramFixture()
	p.classes[0].count = 2
	p.ranges = []snippetRuneRange{{'a', 'b'}, {'d', 'e'}}
	rich.bindings[0].regex = p
	ranged, e := rich.encode()
	if e != nil {
		t.Fatal(e)
	}
	cases = append(cases, ranged)
	rangeAt := int(binary.LittleEndian.Uint32(ranged[36:])) + 48 + 14*16 + 8
	for _, v := range []struct {
		at    int
		value uint32
	}{{rangeAt + 8, 'c'}, {rangeAt, 0xd800}, {rangeAt + 4, 0xe000}, {rangeAt + 12, 0x110000}} {
		b := bytes.Clone(ranged)
		binary.LittleEndian.PutUint32(b[v.at:], v.value)
		cases = append(cases, b)
	}
	return cases
}

func snippetPortableFixtures(t testing.TB) ([]byte, []byte) {
	t.Helper()
	var bases [][]byte
	var rows []snippetPortableRow
	for _, data := range snippetPortableCases(t) {
		base, patch, value := -1, -1, 0
		for j, b := range bases {
			if len(b) < len(data) {
				continue
			}
			at := -1
			for i, v := range data {
				if v != b[i] {
					if at >= 0 {
						at = -2
						break
					}
					at = i
				}
			}
			if at != -2 {
				base = j
				patch = at
				if at >= 0 {
					value = int(data[at])
				}
				break
			}
		}
		if base < 0 {
			base = len(bases)
			bases = append(bases, data)
		}
		valid, offset := 1, 0
		if _, e := decodeSnippetTransformPayload(data); e != nil {
			valid = 0
			var detail *snippetTransformPayloadError
			if !errors.As(e, &detail) {
				t.Fatal(e)
			}
			offset = detail.Offset
		}
		rows = append(rows, snippetPortableRow{base, len(data), patch, value, valid, offset})
	}
	var c, r bytes.Buffer
	c.WriteString("/* Generated by TestSnippetTransformPortableFixtureExport. */\n")
	r.WriteString("// Generated by TestSnippetTransformPortableFixtureExport.\n")
	for i, b := range bases {
		n := len(b)
		if n == 0 {
			n = 1
		}
		zero := true
		for _, v := range b {
			if v != 0 {
				zero = false
				break
			}
		}
		fmt.Fprintf(&c, "static const unsigned char st_base_%d[%d] = {", i, n)
		fmt.Fprintf(&r, "static ST_BASE_%d: [u8; %d] = ", i, len(b))
		if zero {
			c.WriteString("0};\n")
			fmt.Fprintf(&r, "[0; %d];\n", len(b))
			continue
		}
		r.WriteString("[")
		for j, v := range b {
			if j%24 == 0 {
				c.WriteString("\n")
				r.WriteString("\n")
			}
			fmt.Fprintf(&c, "%d,", v)
			fmt.Fprintf(&r, "%d,", v)
		}
		c.WriteString("\n};\n")
		r.WriteString("\n];\n")
	}
	c.WriteString("static const struct st_fixture st_fixtures[] = {\n")
	r.WriteString("static ST_FIXTURES: &[Fixture] = &[\n")
	for _, row := range rows {
		fmt.Fprintf(&c, "{st_base_%d,%d,%d,%d,%d,%d},\n", row.base, row.length, row.patch, row.value, row.valid, row.offset)
		fmt.Fprintf(&r, "Fixture { base: &ST_BASE_%d, len: %d, patch: %d, value: %d, valid: %t, offset: %d },\n", row.base, row.length, row.patch, row.value, row.valid != 0, row.offset)
	}
	c.WriteString("};\n")
	r.WriteString("];\n")
	return c.Bytes(), r.Bytes()
}

func TestSnippetTransformPortableFixtureExport(t *testing.T) {
	c, r := snippetPortableFixtures(t)
	c2, r2 := snippetPortableFixtures(t)
	if !bytes.Equal(c, c2) || !bytes.Equal(r, r2) {
		t.Fatal("nondeterministic export")
	}
	for name, data := range map[string][]byte{"RHUN_TRANSFORM_C_FIXTURES_OUT": c, "RHUN_TRANSFORM_RUST_FIXTURES_OUT": r} {
		if path := os.Getenv(name); path != "" {
			if e := snippetRegexWriteExport(path, data); e != nil {
				t.Fatal(e)
			}
		}
	}
}
